-- Ket qua 5 TRIGGER (chay SAU 10_sp.sql, tren ban sao)
USE QUANLYTHUVIEN_BAOCAO
SET NOCOUNT ON
DECLARE @hom DATE = CAST(GETDATE() AS DATE)

PRINT '=== T1 TRG_CUONSACH_CAPNHATSL (them cuon CS999 cho DS009) ==='
SELECT MADS, TENDS, SOLUONG, SLCON FROM DAUSACH WHERE MADS = 'DS009'
INSERT INTO CUONSACH (MACS, MADS, VITRI) VALUES ('CS999', 'DS009', N'Kệ A3')
SELECT MADS, TENDS, SOLUONG, SLCON FROM DAUSACH WHERE MADS = 'DS009'
UPDATE CUONSACH SET TINHTRANG = N'Hư hỏng' WHERE MACS = 'CS999'
SELECT MADS, TENDS, SOLUONG, SLCON FROM DAUSACH WHERE MADS = 'DS009'

PRINT '=== T2 TRG_PHIEUMUON_KIEMTRA ==='
SELECT MADG, NGAYHETHAN, TONGNO FROM DOCGIA WHERE MADG IN ('DG006', 'DG009')
BEGIN TRY
  INSERT INTO PHIEUMUON (MAPM, MADG, NGAYMUON, HANTRA) VALUES ('PM9901', 'DG006', @hom, DATEADD(DAY, 14, @hom))
END TRY BEGIN CATCH SELECT 'DG006' AS MADG, ERROR_MESSAGE() AS THONGBAO END CATCH
BEGIN TRY
  INSERT INTO PHIEUMUON (MAPM, MADG, NGAYMUON, HANTRA) VALUES ('PM9902', 'DG009', @hom, DATEADD(DAY, 14, @hom))
END TRY BEGIN CATCH SELECT 'DG009' AS MADG, ERROR_MESSAGE() AS THONGBAO END CATCH
SELECT COUNT(*) AS SOPHIEU_PM990x FROM PHIEUMUON WHERE MAPM LIKE 'PM990%'

PRINT '=== T3 TRG_CTPM_MUONSACH (them CS015 - Mat, va CS001 - dang muon vao PM0329) ==='
SELECT MACS, TINHTRANG FROM CUONSACH WHERE MACS IN ('CS015', 'CS001')
BEGIN TRY
  INSERT INTO CTPHIEUMUON (MAPM, MACS) VALUES ('PM0329', 'CS015')
END TRY BEGIN CATCH SELECT 'CS015' AS MACS, ERROR_MESSAGE() AS THONGBAO END CATCH
BEGIN TRY
  INSERT INTO PHIEUMUON (MAPM, MADG, NGAYMUON, HANTRA) VALUES ('PM9903', 'DG012', @hom, DATEADD(DAY, 14, @hom))
  INSERT INTO CTPHIEUMUON (MAPM, MACS) VALUES ('PM9903', 'CS001')
END TRY BEGIN CATCH SELECT 'CS001' AS MACS, ERROR_MESSAGE() AS THONGBAO END CATCH
SELECT COUNT(*) AS SODONG FROM CTPHIEUMUON WHERE MAPM IN ('PM0329', 'PM9903')

PRINT '=== T4 TRG_CTPM_TRASACH (tra CS003 cua PM0014: tre han + hu hong) ==='
SELECT PM.MAPM, PM.MADG, PM.HANTRA, CT.MACS, CS.TINHTRANG, DS.GIA, PM.TINHTRANG AS TTPHIEU
FROM CTPHIEUMUON CT JOIN PHIEUMUON PM ON CT.MAPM = PM.MAPM JOIN CUONSACH CS ON CT.MACS = CS.MACS JOIN DAUSACH DS ON CS.MADS = DS.MADS
WHERE CT.MAPM = 'PM0014'
UPDATE CTPHIEUMUON SET NGAYTRA = @hom, TINHTRANGTRA = N'Hư hỏng' WHERE MAPM = 'PM0014' AND MACS = 'CS003'
SELECT PM.MAPM, CT.MACS, CT.NGAYTRA, CT.TINHTRANGTRA, CS.TINHTRANG, PM.TINHTRANG AS TTPHIEU
FROM CTPHIEUMUON CT JOIN PHIEUMUON PM ON CT.MAPM = PM.MAPM JOIN CUONSACH CS ON CT.MACS = CS.MACS
WHERE CT.MAPM = 'PM0014'
SELECT MAPP, MAPM, MACS, LYDO, SOTIEN FROM PHIEUPHAT WHERE MAPM = 'PM0014'
BEGIN TRY
  UPDATE CTPHIEUMUON SET NGAYTRA = @hom, TINHTRANGTRA = N'Bình thường' WHERE MAPM = 'PM0014' AND MACS = 'CS003'
END TRY BEGIN CATCH SELECT ERROR_MESSAGE() AS THONGBAO_SUALAI END CATCH

PRINT '=== T5 TRG_PHIEUPHAT_TONGNO (DG014 thanh toan PP0013) ==='
SELECT PP.MAPP, PP.LYDO, PP.SOTIEN, PP.DATHANHTOAN FROM PHIEUPHAT PP JOIN PHIEUMUON PM ON PP.MAPM = PM.MAPM
WHERE PM.MADG = 'DG014' AND PP.DATHANHTOAN = 0
SELECT MADG, TONGNO FROM DOCGIA WHERE MADG = 'DG014'
UPDATE PHIEUPHAT SET DATHANHTOAN = 1 WHERE MAPP = 'PP0013'
SELECT MADG, TONGNO FROM DOCGIA WHERE MADG = 'DG014'
