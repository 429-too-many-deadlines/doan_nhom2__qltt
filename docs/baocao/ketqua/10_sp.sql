EXEC @kq = SP_THEMDOCGIA 'DG999', N'Trần Thị Mai', '2004-03-15', N'Nữ', N'Thủ Đức, TpHCM', '0909123456', NULL
SELECT @kq AS KETQUA_LAN1
EXEC @kq = SP_THEMDOCGIA 'DG999', N'Trần Thị Mai', '2004-03-15', N'Nữ', N'Thủ Đức, TpHCM', '0909123456', NULL
SELECT @kq AS KETQUA_LAN2
SELECT MADG, HOTEN, NGAYLAPTHE, NGAYHETHAN, TONGNO FROM DOCGIA WHERE MADG = 'DG999'
SELECT COUNT(*) AS SODOCGIA_SAU FROM DOCGIA

PRINT '=== SP2 SP_LAPPHIEUMUON ==='
DECLARE @madg CHAR(5), @ds VARCHAR(200), @mapm CHAR(6), @kq2 INT
SELECT TOP 1 @madg = MADG FROM DOCGIA
WHERE TONGNO = 0 AND NGAYHETHAN >= CAST(GETDATE() AS DATE) AND MADG <> 'DG999'
  AND NOT EXISTS (SELECT * FROM PHIEUMUON PM WHERE PM.MADG = DOCGIA.MADG)
ORDER BY MADG
SELECT @ds = STRING_AGG(MACS, ',') WITHIN GROUP (ORDER BY MACS)
FROM (SELECT TOP 2 MACS FROM CUONSACH WHERE TINHTRANG = N'Có sẵn' ORDER BY MACS) T
SELECT @madg AS MADG, @ds AS DSMACS
SELECT CS.MACS, CS.MADS, CS.TINHTRANG, DS.SLCON FROM CUONSACH CS JOIN DAUSACH DS ON CS.MADS = DS.MADS
WHERE CS.MACS IN (SELECT value FROM STRING_SPLIT(@ds, ','))
EXEC @kq2 = SP_LAPPHIEUMUON @madg, @ds, @mapm OUTPUT
SELECT @kq2 AS KETQUA, @mapm AS MAPM_MOI
SELECT * FROM PHIEUMUON WHERE MAPM = @mapm
SELECT * FROM CTPHIEUMUON WHERE MAPM = @mapm
SELECT CS.MACS, CS.MADS, CS.TINHTRANG, DS.SLCON FROM CUONSACH CS JOIN DAUSACH DS ON CS.MADS = DS.MADS
WHERE CS.MACS IN (SELECT value FROM STRING_SPLIT(@ds, ','))

PRINT '=== SP3 SP_TRASACH (PM0011 / CS011, qua han) ==='
DECLARE @phat MONEY, @kq3 INT
SELECT PM.MAPM, CT.MACS, PM.MADG, PM.HANTRA, CT.NGAYTRA, CS.TINHTRANG
FROM CTPHIEUMUON CT JOIN PHIEUMUON PM ON CT.MAPM = PM.MAPM JOIN CUONSACH CS ON CT.MACS = CS.MACS
WHERE CT.MAPM = 'PM0011' AND CT.MACS = 'CS011'
SELECT MADG, TONGNO FROM DOCGIA WHERE MADG = 'DG001'
EXEC @kq3 = SP_TRASACH 'PM0011', 'CS011', N'Bình thường', @phat OUTPUT
SELECT @kq3 AS KETQUA, @phat AS TIENPHAT
SELECT CT.MAPM, CT.MACS, CT.NGAYTRA, CT.TINHTRANGTRA, CS.TINHTRANG, PM.TINHTRANG AS TINHTRANGPHIEU
FROM CTPHIEUMUON CT JOIN PHIEUMUON PM ON CT.MAPM = PM.MAPM JOIN CUONSACH CS ON CT.MACS = CS.MACS
WHERE CT.MAPM = 'PM0011' AND CT.MACS = 'CS011'
SELECT * FROM PHIEUPHAT WHERE MAPM = 'PM0011'
SELECT MADG, TONGNO FROM DOCGIA WHERE MADG = 'DG001'

PRINT '=== SP4 SP_THANHTOANPHAT (DG010) ==='
DECLARE @tien MONEY, @kq4 INT
SELECT PP.MAPP, PP.MAPM, PP.LYDO, PP.SOTIEN, PP.DATHANHTOAN
FROM PHIEUPHAT PP JOIN PHIEUMUON PM ON PP.MAPM = PM.MAPM WHERE PM.MADG = 'DG010'
SELECT MADG, TONGNO FROM DOCGIA WHERE MADG = 'DG010'
EXEC @kq4 = SP_THANHTOANPHAT 'DG010', @tien OUTPUT
SELECT @kq4 AS KETQUA, @tien AS DATHANHTOAN
SELECT PP.MAPP, PP.SOTIEN, PP.DATHANHTOAN
FROM PHIEUPHAT PP JOIN PHIEUMUON PM ON PP.MAPM = PM.MAPM WHERE PM.MADG = 'DG010'
SELECT MADG, TONGNO FROM DOCGIA WHERE MADG = 'DG010'
EXEC @kq4 = SP_THANHTOANPHAT 'DG010', @tien OUTPUT
SELECT @kq4 AS KETQUA_LAN2

PRINT '=== SP5 SP_THONGKETHANG (9/2026) ==='
DECLARE @sp INT, @sl INT, @tp MONEY
EXEC SP_THONGKETHANG 9, 2026, @sp OUTPUT, @sl OUTPUT, @tp OUTPUT
SELECT @sp AS SOPHIEU, @sl AS SOLUOTSACH, @tp AS TIENPHAT
