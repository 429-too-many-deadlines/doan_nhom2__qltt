GO
PRINT '### SP2 LAPPHIEUMUON'
BEGIN TRAN
SELECT MADG,NGAYHETHAN,TONGNO FROM DOCGIA WHERE MADG='DG012'
SELECT MACS,TINHTRANG FROM CUONSACH WHERE MACS IN ('CS004','CS005')
SELECT MADS,TENDS,SOLUONG,SLCON FROM DAUSACH WHERE MADS='DS002'
DECLARE @MAPM CHAR(6), @KQ INT
EXEC @KQ = SP_LAPPHIEUMUON 'DG012', 'CS004,CS005', @MAPM OUTPUT
SELECT @KQ AS KETQUA, @MAPM AS MAPM
SELECT * FROM PHIEUMUON WHERE MAPM=@MAPM
SELECT MACS,TINHTRANG FROM CUONSACH WHERE MACS IN ('CS004','CS005')
SELECT MADS,TENDS,SOLUONG,SLCON FROM DAUSACH WHERE MADS='DS002'
ROLLBACK
GO
PRINT '### SP3 TRASACH'
BEGIN TRAN
SELECT MADG,TONGNO FROM DOCGIA WHERE MADG='DG014'
SELECT CT.*, PM.HANTRA FROM CTPHIEUMUON CT JOIN PHIEUMUON PM ON CT.MAPM=PM.MAPM WHERE CT.MAPM='PM0014'
DECLARE @PHAT MONEY, @KQ INT
EXEC @KQ = SP_TRASACH 'PM0014', 'CS003', N'Hư hỏng', @PHAT OUTPUT
SELECT @KQ AS KETQUA, @PHAT AS TIENPHAT
SELECT MAPP,MAPM,MACS,NGAYLAP,LYDO,SOTIEN,DATHANHTOAN FROM PHIEUPHAT WHERE MAPM='PM0014'
SELECT MACS,TINHTRANG FROM CUONSACH WHERE MACS='CS003'
SELECT MAPM,TINHTRANG FROM PHIEUMUON WHERE MAPM='PM0014'
SELECT MADG,TONGNO FROM DOCGIA WHERE MADG='DG014'
ROLLBACK
GO
PRINT '### SP4 THANHTOANPHAT'
BEGIN TRAN
SELECT MADG,TONGNO FROM DOCGIA WHERE MADG='DG009'
SELECT PP.MAPP,PP.LYDO,PP.SOTIEN,PP.DATHANHTOAN FROM PHIEUPHAT PP JOIN PHIEUMUON PM ON PP.MAPM=PM.MAPM WHERE PM.MADG='DG009'
DECLARE @TIEN MONEY, @KQ INT
EXEC @KQ = SP_THANHTOANPHAT 'DG009', @TIEN OUTPUT
SELECT @KQ AS KETQUA, @TIEN AS DATHANHTOAN
SELECT PP.MAPP,PP.LYDO,PP.SOTIEN,PP.DATHANHTOAN FROM PHIEUPHAT PP JOIN PHIEUMUON PM ON PP.MAPM=PM.MAPM WHERE PM.MADG='DG009'
SELECT MADG,TONGNO FROM DOCGIA WHERE MADG='DG009'
EXEC @KQ = SP_THANHTOANPHAT 'DG009', @TIEN OUTPUT
SELECT @KQ AS KETQUA_LAN2
ROLLBACK
GO
