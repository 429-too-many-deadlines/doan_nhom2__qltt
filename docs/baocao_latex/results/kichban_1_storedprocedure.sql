DECLARE @KQ INT
EXEC @KQ = SP_THEMDOCGIA 'DG316', N'Trương Thị Hoa', '2005-05-05', N'Nữ', N'Thủ Đức, TpHCM', '0901234576', NULL
SELECT @KQ AS KETQUA
SELECT MADG,HOTEN,NGSINH,NGAYLAPTHE,NGAYHETHAN,TONGNO FROM DOCGIA WHERE MADG='DG316'
EXEC @KQ = SP_THEMDOCGIA 'DG316', N'Trùng mã', '2005-05-05', N'Nữ', NULL, '0900000000', NULL
