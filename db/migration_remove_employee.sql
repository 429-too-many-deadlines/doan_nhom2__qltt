-- 5. Alter SP_LAPPHIEUMUON
CREATE OR ALTER PROCEDURE SP_LAPPHIEUMUON
@MADG CHAR (5), @DSMACS VARCHAR (200), @MAPM CHAR (6) OUTPUT
AS
BEGIN
	SET NOCOUNT ON;
	SET @MAPM = NULL;
	IF NOT EXISTS (SELECT	*
					FROM		DOCGIA
					WHERE	MADG = @MADG)
		BEGIN
			PRINT N'Độc giả không tồn tại.';
			RETURN 0;
		END
	IF NOT EXISTS (SELECT	*
					FROM		STRING_SPLIT (@DSMACS, ',')
					WHERE	LTRIM(RTRIM(value)) <> '')
		BEGIN
			PRINT N'Phiếu mượn phải có ít nhất một cuốn sách.';
			RETURN 0;
		END
	DECLARE @SONGAY AS INT = 14; 
	BEGIN TRY
		BEGIN TRANSACTION;
		DECLARE @MAX AS INT;
		SELECT	@MAX = ISNULL(MAX(CAST (SUBSTRING(MAPM, 3, 4) AS INT)), 0)
		FROM	PHIEUMUON WITH (UPDLOCK, HOLDLOCK);
		SET @MAPM = 'PM' + RIGHT('0000' + CAST (@MAX + 1 AS VARCHAR (4)), 4);
		INSERT	INTO PHIEUMUON (
			MAPM,
			MADG,
			NGAYMUON,
			HANTRA,
			TINHTRANG
		)
		VALUES                 (@MAPM, @MADG, CAST (GETDATE() AS DATE), DATEADD(DAY, @SONGAY, CAST (GETDATE() AS DATE)), N'Đang mượn');
		INSERT	INTO CTPHIEUMUON (
			MAPM,
			MACS
		)
		SELECT	DISTINCT @MAPM,
						LTRIM(RTRIM(value))
		FROM	STRING_SPLIT (@DSMACS, ',')
		WHERE	LTRIM(RTRIM(value)) <> '';
		COMMIT TRANSACTION;
		PRINT N'Lập phiếu mượn ' + @MAPM + N' thành công.';
		RETURN 1;
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0
			ROLLBACK;
		SET @MAPM = NULL;
		DECLARE @LOI AS NVARCHAR (4000) = ERROR_MESSAGE();
		RAISERROR (@LOI, 16, 1);
		RETURN 0;
	END CATCH
END
GO

-- 6. Alter SP_LAYDANHSACHPHIEUMUON
CREATE OR ALTER PROCEDURE SP_LAYDANHSACHPHIEUMUON
	@PageNumber INT = 1,
	@PageSize INT = 10
AS
BEGIN
	SET NOCOUNT ON;
	SELECT PM.MAPM, PM.MADG, DG.HOTEN AS TENDG, PM.NGAYMUON, PM.HANTRA, PM.TINHTRANG,
	       CT.MACS, CT.NGAYTRA, CT.TINHTRANGTRA,
	       COUNT(*) OVER() AS TotalRecord
	FROM PHIEUMUON PM
	LEFT JOIN DOCGIA DG ON PM.MADG = DG.MADG
	LEFT JOIN CTPHIEUMUON CT ON PM.MAPM = CT.MAPM
	ORDER BY PM.NGAYMUON DESC, PM.MAPM DESC
	OFFSET (@PageNumber - 1) * @PageSize ROWS
	FETCH NEXT @PageSize ROWS ONLY;
END
GO

-- 7. Fix Authentication SPs
CREATE OR ALTER PROCEDURE SP_DANGNHAP
	@TENDANGNHAP	VARCHAR(30),
	@MATKHAU		NVARCHAR(100),
	@KETQUA			INT OUTPUT
AS
BEGIN
	SET NOCOUNT ON;
	SET @KETQUA = 0;
	IF NOT EXISTS (SELECT * FROM TAIKHOAN WHERE TENDANGNHAP = @TENDANGNHAP AND MATKHAU = HASHBYTES('SHA2_256', @MATKHAU))
	BEGIN
		SELECT TOP 0 TENDANGNHAP FROM TAIKHOAN;
		RETURN;
	END
	IF EXISTS (SELECT * FROM TAIKHOAN WHERE TENDANGNHAP = @TENDANGNHAP AND TRANGTHAI = 0)
	BEGIN
		SET @KETQUA = 1;
		SELECT TOP 0 TENDANGNHAP FROM TAIKHOAN;
		RETURN;
	END
	SET @KETQUA = 2;
	SELECT TENDANGNHAP, 'Admin' AS HOTEN FROM TAIKHOAN WHERE TENDANGNHAP = @TENDANGNHAP;
END
GO
CREATE OR ALTER PROCEDURE SP_TAOTAIKHOAN
	@TENDANGNHAP	VARCHAR(30),
	@MATKHAU		NVARCHAR(100)
AS
BEGIN
	SET NOCOUNT ON;
	IF EXISTS (SELECT * FROM TAIKHOAN WHERE TENDANGNHAP = @TENDANGNHAP)
	BEGIN
		PRINT N'Tên đăng nhập đã tồn tại.';
		RETURN 0;
	END
	INSERT INTO TAIKHOAN (TENDANGNHAP, MATKHAU) VALUES (@TENDANGNHAP, HASHBYTES('SHA2_256', @MATKHAU));
	RETURN 1;
END
GO
