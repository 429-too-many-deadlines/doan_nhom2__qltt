('GIANGVIEN','DELETE GIAOVIEN','DELETE FROM GIAOVIEN WHERE MSGV = 201'),
('SINHVIEN','SELECT SINHVIEN','DECLARE @n INT; SELECT @n = COUNT(*) FROM SINHVIEN'),
('SINHVIEN','SELECT HOIDONG','DECLARE @n INT; SELECT @n = COUNT(*) FROM HOIDONG'),
('SINHVIEN','SELECT DETAI','DECLARE @n INT; SELECT @n = COUNT(*) FROM DETAI'),
('SINHVIEN','SELECT GIAOVIEN','DECLARE @n INT; SELECT @n = COUNT(*) FROM GIAOVIEN'),
('SINHVIEN','UPDATE SINHVIEN','UPDATE SINHVIEN SET SODT = SODT'),
('SINHVIEN','DELETE SINHVIEN','DELETE FROM SINHVIEN')

DECLARE c CURSOR LOCAL FOR SELECT u, op, sql FROM @cases
OPEN c
FETCH NEXT FROM c INTO @u, @op, @sql
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @ok = N'Được phép'
    BEGIN TRY
        BEGIN TRAN
        EXEC('EXECUTE AS USER = ''' + @u + '''; ' + @sql + N'; REVERT;')
        ROLLBACK
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0 ROLLBACK
        REVERT
        SET @ok = N'BỊ TỪ CHỐI'
    END CATCH
    INSERT @t VALUES (@u, @op, @ok)
    FETCH NEXT FROM c INTO @u, @op, @sql
END
CLOSE c DEALLOCATE c
SELECT [User], [Thao tác], [Kết quả] FROM @t ORDER BY Stt
GO
