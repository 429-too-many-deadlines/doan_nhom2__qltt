SELECT dp.name AS [User], p.state_desc AS [Loại], p.permission_name AS [Quyền],
       CASE p.class WHEN 3 THEN 'SCHEMA::' + SCHEMA_NAME(p.major_id)
                    ELSE OBJECT_NAME(p.major_id) END AS [Đối tượng]
FROM sys.database_permissions p
JOIN sys.database_principals dp ON dp.principal_id = p.grantee_principal_id
WHERE dp.name IN ('GIANGVIEN','GIAOVU','SINHVIEN') AND p.class IN (1,3)
ORDER BY dp.name, p.state_desc, [Đối tượng], p.permission_name
GO

DECLARE @t TABLE (Stt INT IDENTITY, [User] VARCHAR(20), [Thao tác] VARCHAR(40), [Kết quả] NVARCHAR(100))
DECLARE @u VARCHAR(20), @sql NVARCHAR(300), @op VARCHAR(40), @ok NVARCHAR(100)

DECLARE @cases TABLE (u VARCHAR(20), op VARCHAR(40), sql NVARCHAR(300))
INSERT @cases VALUES
('GIAOVU','SELECT HOCVI','DECLARE @n INT; SELECT @n = COUNT(*) FROM HOCVI'),
('GIAOVU','UPDATE SINHVIEN','UPDATE SINHVIEN SET SODT = SODT'),
('GIAOVU','INSERT HOCVI','INSERT HOCVI VALUES (9, N''x'')'),
('GIAOVU','DELETE HOCVI','DELETE FROM HOCVI WHERE MSHV = 5'),
